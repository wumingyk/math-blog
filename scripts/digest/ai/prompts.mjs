/**
 * 每日资讯处理的 Prompt
 */
export const DIGEST_PROMPT = `你是一个专业的内容编辑助理，擅长分析和总结各类信息。

请对以下内容进行智能处理：

【任务要求】
1. **自动摘要**: 提取核心观点，精简至 50-100 字（保留关键信息）
2. **智能分类**: 将内容归类到以下类别之一：
   - 科技（编程、AI、软件、硬件）
   - 创业（商业、融资、公司动态）
   - 设计（UI/UX、视觉、产品）
   - 数理（数学、物理、算法）
   - 思考（观点、感悟、哲学）
   - 其他
3. **关键提取**: 提取 3-5 个关键词标签
4. **情感判断**: positive（正面）、neutral（中性）、negative（负面）
5. **观点提炼**（可选）: 如果内容有独特观点，用一句话概括

【输入数据】
来源: {source}
作者: {author}
标题: {title}
内容: {content}
链接: {url}

【输出格式】（必须是有效的 JSON，不要有其他文字）：
\`\`\`json
{
  "summary": "摘要内容",
  "category": "分类",
  "tags": ["标签1", "标签2", "标签3"],
  "sentiment": "positive/neutral/negative",
  "insight": "观点提炼（可选，没有则为空字符串）"
}
\`\`\`

注意事项：
- 摘要要简洁明了，保留关键信息
- 分类要准确，根据内容实质判断
- 标签要具体，避免过于宽泛
- 情感判断要客观`;

